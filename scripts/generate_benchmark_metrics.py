"""Generate benchmark metrics as OpenMetrics text."""

import json
import typing
from collections import defaultdict

import click


def _benchmark_group_name(benchmark: dict[str, typing.Any]) -> str:
    """Get the name of a benchmark without its parameters.

    Args:
        benchmark (dict[str, typing.Any]): A single benchmark entry
            in the JSON output of pytest-benchmark.

    Returns:
        str: Name of the benchmark shared among its parameters.
    """
    return str(benchmark["name"]).split("[", 1)[0]


def _escape_label_value(value: str) -> str:
    """Escape a string to be used as a label value in OpenMetrics text format.

    Args:
        value (str): Value to escape.

    Returns:
        str: Escaped value.
    """
    return value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def _write_metric(
    output: typing.TextIO,
    *,
    name: str,
    help_text: str,
    values: dict[str, float],
) -> None:
    """Write a gauge metric in OpenMetrics text format.

    Args:
        output (typing.TextIO): Output stream to write the metric to.
        name (str): Name of the metric.
        help_text (str): Description of the metric.
        values (dict[str, float]): Values of the metric for each
            benchmark, keyed by the name of the benchmark.
    """
    output.write(f"# TYPE {name} gauge\n")
    output.write(f"# HELP {name} {help_text}\n")
    for benchmark_name in sorted(values):
        label_value = _escape_label_value(benchmark_name)
        output.write(f'{name}{{name="{label_value}"}} {values[benchmark_name]}\n')


@click.command()
@click.argument("input", type=click.File("r"))
@click.argument("output", type=click.File("w"))
def generate_benchmark_metrics(input: typing.TextIO, output: typing.TextIO) -> None:
    """Generate benchmark metrics as OpenMetrics text.

    This command reads the JSON file (INPUT) generated by pytest-benchmark,
    and for every benchmark, ignoring its parameters,
    calculates the largest value of the maximum processing time
    and the largest value of the average processing time
    among its parameters.
    The result is written to OUTPUT in OpenMetrics text format.
    """
    data = json.load(input)

    max_times: dict[str, float] = defaultdict(float)
    mean_times: dict[str, float] = defaultdict(float)
    for benchmark in data["benchmarks"]:
        group_name = _benchmark_group_name(benchmark)
        stats = benchmark["stats"]
        max_times[group_name] = max(max_times[group_name], stats["max"] * 1000.0)
        mean_times[group_name] = max(mean_times[group_name], stats["mean"] * 1000.0)

    _write_metric(
        output,
        name="func_sketch_benchmark_max_milliseconds",
        help_text=(
            "Largest value of the maximum processing time in milliseconds "
            "among the parameters of each benchmark."
        ),
        values=max_times,
    )
    _write_metric(
        output,
        name="func_sketch_benchmark_mean_max_milliseconds",
        help_text=(
            "Largest value of the average processing time in milliseconds "
            "among the parameters of each benchmark."
        ),
        values=mean_times,
    )
    output.write("# EOF\n")


if __name__ == "__main__":
    generate_benchmark_metrics()
